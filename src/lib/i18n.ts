// Reverse index so a raw English string can be translated directly. This is for
// text declared outside a component (config arrays, alert copy) where a key
// lookup isn't practical — tx('Bible Study') returns the Spanish equivalent.
const byEnglish: Record<string, Record<Lang, string>> = {};
for (const key in translations) {
  byEnglish[translations[key].English] = translations[key];
}

export function useTranslation() {
  const appSettings = useSettings();
  const lang: Lang = appSettings.appearance.language === 'Español' ? 'Español' : 'English';

  function t(key: keyof typeof translations): string {
    return translations[key]?.[lang] || translations[key]?.English || String(key);
  }

  /** Translate a raw English string; falls back to the original if untranslated. */
  function tx(english: string): string {
    if (!english) return english;
    return byEnglish[english]?.[lang] || english;
  }

  return { t, tx, lang };
}
